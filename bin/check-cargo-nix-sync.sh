#!/usr/bin/env bash
# Check if Cargo.nix is in sync with Cargo.lock
# This prevents committing outdated Cargo.nix files

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

cd "$PROJECT_ROOT"

# Check if both files exist
if [[ ! -f Cargo.nix ]]; then
  echo "Error: Cargo.nix not found. Please regenerate it with: nix shell github:cargo2nix/cargo2nix/release-0.12 -c cargo2nix"
  exit 1
fi

if [[ ! -f Cargo.lock ]]; then
  echo "Error: Cargo.lock not found"
  exit 1
fi

# Extract the hash values from both files
# From Cargo.nix: looks like "Cargo.nix HASH is out of sync with Cargo.lock HASH"
# We need to extract the actual hashes

CARGO_NIX_HASH=$(head -1 Cargo.nix | grep -oP '@generated by cargo2nix \K[0-9.]+')
CARGO_LOCK_CONTENT=$(head -c 1000 Cargo.lock)

# Try to evaluate Cargo.nix with nix to check if it's in sync
# This is the most reliable check since nix will fail if they're out of sync
if nix eval --raw -f '{ cargo2nix }: import cargo2nix {}' .# 2>&1 | grep -q "out of sync"; then
  echo "Error: Cargo.nix is out of sync with Cargo.lock"
  echo ""
  echo "To regenerate Cargo.nix, run:"
  echo "  rm Cargo.nix && nix shell github:cargo2nix/cargo2nix/release-0.12 -c cargo2nix"
  echo ""
  echo "Or simply:"
  echo "  nix shell github:cargo2nix/cargo2nix/release-0.12 -c cargo2nix"
  exit 1
fi

# Alternative: Try to build the devshell (which will fail if out of sync)
if ! timeout 30 nix develop --command true 2>&1 | grep -q "out of sync"; then
  # No "out of sync" error found, check passed
  exit 0
fi

echo "Error: Cargo.nix is out of sync with Cargo.lock"
echo ""
echo "To regenerate Cargo.nix, run:"
echo "  rm Cargo.nix && nix shell github:cargo2nix/cargo2nix/release-0.12 -c cargo2nix"
echo ""
echo "Or simply:"
echo "  nix shell github:cargo2nix/cargo2nix/release-0.12 -c cargo2nix"
exit 1
